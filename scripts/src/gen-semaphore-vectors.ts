// Writes contracts/test/vectors/semaphore.json: fixed demo identities, groups of depth 1 to 4, and one real proof per
// group, made with the pinned local artifacts. contracts/test/Semaphore.t.sol rebuilds each group on-chain, checks the
// Merkle root matches (TypeScript and Solidity LeanIMT agree) and verifies each proof (each zkey matches
// SemaphoreVerifier). Groth16 proofs are randomised, so re-running changes the proofs but not the roots.
//
//   bun scripts/src/gen-semaphore-vectors.ts
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { feedbackScope, Group, Identity, proveMembership, treeDepth } from "@veil8004/sdk/semaphore";

// Fixed, public demo secrets: these identities exist only for test vectors.
const identities = Array.from({ length: 9 }, (_, i) => new Identity(`veil8004-test-vector-identity-${i}`));
const AGENT_ID = 1n;
const EPOCH = 488_000n;
const SCORE = 4n;
const scope = feedbackScope(AGENT_ID, EPOCH);

const cases = [];
// Group sizes 2, 3, 5, 9 give depths 1, 2, 3, 4. The prover is the last member.
for (const size of [2, 3, 5, 9]) {
  const members = identities.slice(0, size);
  const group = new Group(members.map((m) => m.commitment));
  const proof = await proveMembership(members[size - 1]!, group, SCORE, scope);
  cases.push({ name: `depth ${treeDepth(size)}`, members: members.map((_, i) => i), prover: size - 1, root: group.root.toString(), proof });
}
// S-2: identity 0 in a second group ({0, 2}) with the same scope yields the same nullifier as in group {0, 1}.
{
  const group = new Group([identities[0]!.commitment, identities[2]!.commitment]);
  const proof = await proveMembership(identities[0]!, group, SCORE, scope);
  cases.push({ name: "identity 0 in another group", members: [0, 2], prover: 0, root: group.root.toString(), proof });
}
{
  const group = new Group([identities[0]!.commitment, identities[1]!.commitment]);
  const proof = await proveMembership(identities[0]!, group, SCORE, scope);
  cases.push({ name: "identity 0 in group {0, 1}", members: [0, 1], prover: 0, root: group.root.toString(), proof });
}

const file = {
  _comment:
    "Generated by scripts/src/gen-semaphore-vectors.ts with @semaphore-protocol/core 4.14.3 and the pinned artifacts (sdk/src/snarkArtifacts.ts). Checked by test/Semaphore.t.sol.",
  agentId: AGENT_ID.toString(),
  epoch: EPOCH.toString(),
  score: SCORE.toString(),
  scope: scope.toString(),
  identityCommitments: identities.map((i) => i.commitment.toString()),
  cases,
};
const out = join(import.meta.dir, "../../contracts/test/vectors/semaphore.json");
writeFileSync(out, `${JSON.stringify(file, null, 2)}\n`);
console.log(`wrote ${cases.length} cases to ${out}`);
process.exit(0); // snarkjs leaves worker threads running
