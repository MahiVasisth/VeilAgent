// Writes contracts/test/vectors/feedback.json: real Semaphore proofs for the anonymous-feedback scenario that
// contracts/test/AnonymousFeedback.t.sol replays (Phase 5). Agent ids and the epoch must match that test.
//
//   Receipts in epoch E, category SANCTIONS ("sanctions-screening"), in this order:
//     task 1: client 0 hires alice   task 2: client 1 hires bob   task 3: client 2 hires alice
//   and in category KYC ("kyc-review"): task 4: client 0 hires alice.
//   Client 3 never completes a job.
//
//   bun scripts/src/gen-feedback-vectors.ts
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { feedbackScope, Group, Identity, proveMembership } from "@veil8004/sdk/semaphore";

// Fixed, public demo secrets: these identities exist only for test vectors.
const clients = Array.from({ length: 4 }, (_, i) => new Identity(`veil8004-feedback-client-${i}`));
const c = clients.map((i) => i.commitment);
const EPOCH = 488_000n;
const EPOCH_LENGTH = 3600n;
const AGENTS = { alice: 2n, bob: 3n, carol: 4n }; // ERC-8004 ids in the test fixture

const groups = {
  sanctionsFirst: new Group([c[0]!]), // after task 1 only
  sanctions: new Group([c[0]!, c[1]!, c[2]!]),
  kyc: new Group([c[0]!]),
  forged: new Group([c[0]!, c[1]!, c[3]!]), // not on-chain: client 3 has no receipt
};

const plan = [
  ["early", 0, "sanctionsFirst", "alice", 5n],
  ["alice2", 2, "sanctions", "alice", 4n],
  ["bob", 1, "sanctions", "bob", 4n],
  ["again", 0, "sanctions", "alice", 1n],
  ["crossGroup", 0, "kyc", "alice", 2n],
  ["carol", 1, "sanctions", "carol", 2n],
  ["forged", 3, "forged", "alice", 3n],
] as const;

const proofs: Record<string, unknown> = {};
for (const [name, client, group, agent, score] of plan) {
  proofs[name] = { client, group, agent, score: score.toString(), ...(await proveMembership(clients[client]!, groups[group], score, feedbackScope(AGENTS[agent], EPOCH))) };
}

const file = {
  _comment:
    "Generated by scripts/src/gen-feedback-vectors.ts (SDK prover, pinned artifacts). Replayed by test/AnonymousFeedback.t.sol.",
  epoch: EPOCH.toString(),
  epochLength: EPOCH_LENGTH.toString(),
  agents: Object.fromEntries(Object.entries(AGENTS).map(([k, v]) => [k, v.toString()])),
  identityCommitments: c.map(String),
  roots: Object.fromEntries(Object.entries(groups).map(([k, g]) => [k, g.root.toString()])),
  proofs,
};
const out = join(import.meta.dir, "../../contracts/test/vectors/feedback.json");
writeFileSync(out, `${JSON.stringify(file, null, 2)}\n`);
console.log(`wrote ${plan.length} proofs to ${out}`);
process.exit(0);
