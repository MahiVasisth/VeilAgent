// Writes the TypeScript ABIs from Foundry artifacts, so they can never drift from the contracts we deploy:
//   sdk/src/abi/erc8004.ts  installed ERC-8004 sources (the repo's own abis/ folder is stale: docs/phase0.md I-3)
//   sdk/src/abi/veil.ts     Veil8004 contracts (Phase 2+; SealedBidHiring from Phase 3)
//   sdk/src/abi/semaphore.ts  Semaphore V4 from @semaphore-protocol/contracts (Phase 5, our own deployment)
// Run after `forge build`: bun scripts/src/gen-abis.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "../..");
const out = join(root, "contracts/out");
const groups = {
  "erc8004.ts": {
    source: "erc-8004-contracts sources",
    contracts: {
      identityRegistryAbi: "IdentityRegistryUpgradeable",
      reputationRegistryAbi: "ReputationRegistryUpgradeable",
      validationRegistryAbi: "ValidationRegistryUpgradeable",
    },
  },
  "veil.ts": {
    source: "Veil8004 contracts",
    contracts: {
      policyRegistryAbi: "PolicyRegistry",
      privateValidationRegistryAbi: "PrivateValidationRegistry",
      treasuryActionAbi: "TreasuryAction",
      sealedBidHiringAbi: "SealedBidHiring",
      mockForwarderAbi: "MockForwarder",
      nullifierRegistryAbi: "NullifierRegistry",
      receiptGroupManagerAbi: "ReceiptGroupManager",
      anonymousFeedbackAbi: "AnonymousFeedback",
    },
  },
  "semaphore.ts": {
    source: "@semaphore-protocol/contracts",
    contracts: {
      semaphoreAbi: "Semaphore",
    },
  },
} as const;

for (const [file, group] of Object.entries(groups)) {
  let src = `// GENERATED by scripts/src/gen-abis.ts from contracts/out (${group.source}). Do not edit.\n`;
  for (const [name, contract] of Object.entries(group.contracts)) {
    const artifact = JSON.parse(readFileSync(join(out, `${contract}.sol`, `${contract}.json`), "utf8"));
    src += `\nexport const ${name} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  }
  const target = join(root, "sdk/src/abi", file);
  writeFileSync(target, src);
  console.log(`wrote ${target}`);
}
