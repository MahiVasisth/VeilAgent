// Writes sdk/src/abi/erc8004.ts from the Foundry artifacts of the installed ERC-8004 sources, so the TypeScript
// ABIs can never drift from the contracts we deploy (the repo's own abis/ folder is stale: docs/phase0.md I-3).
// Run after `forge build`: bun scripts/src/gen-abis.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "../..");
const out = join(root, "contracts/out");
const contracts = {
  identityRegistryAbi: "IdentityRegistryUpgradeable",
  reputationRegistryAbi: "ReputationRegistryUpgradeable",
  validationRegistryAbi: "ValidationRegistryUpgradeable",
} as const;

let src = "// GENERATED by scripts/src/gen-abis.ts from contracts/out (erc-8004-contracts sources). Do not edit.\n";
for (const [name, contract] of Object.entries(contracts)) {
  const artifact = JSON.parse(readFileSync(join(out, `${contract}.sol`, `${contract}.json`), "utf8"));
  src += `\nexport const ${name} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
}
const target = join(root, "sdk/src/abi/erc8004.ts");
writeFileSync(target, src);
console.log(`wrote ${target}`);
